export function presentNode(node) {
  const override = overrides[node.id] || {}
  const rawHeading = stripInternalPrefix(override.heading || node.heading || '')
  const heading = node.kind === 'choice' ? rawHeading.replaceAll('你', '我') : rawHeading
  const choiceText = node.kind === 'choice' ? (override.text || node.text || '').replaceAll('你', '我') : (override.text || node.text || '')
  return {
    ...node,
    ...override,
    heading,
    speaker: override.speaker || speakerAliases[node.speaker] || node.speaker,
    source: override.source || sourceAliases[node.source] || node.source,
    orientation: node.orientation ? {
      ...node.orientation,
      kicker: (node.orientation.kicker || '')
        .replace(/^案件起点\s*[｜|]\s*/, '我从这里查起｜')
        .replace(/^转场\s*[｜|]\s*/, '我转去｜')
        .replace(/^临时插曲\s*[｜|]\s*/, '我被来电打断｜'),
      route: (node.orientation.route || '')
        .replaceAll('你的', '我的')
        .replaceAll('你', '我'),
      goal: (node.orientation.goal || '')
        .replaceAll('给玩家', '给后来的人')
        .replaceAll('你的', '我的')
        .replaceAll('你', '我')
    } : node.orientation,
    media: node.media ? { ...node.media, alt: stripInternalPrefix(node.media.alt || '') } : node.media,
    text: choiceText,
    education: override.education || node.education
  }
}
